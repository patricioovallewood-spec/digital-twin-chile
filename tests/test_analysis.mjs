import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {areaHa,enrichCensus,summarize,streetGroups} from '../atlas/analysis.mjs';
import {filterFeatures,csv} from '../atlas/core.mjs';
const read=name=>JSON.parse(readFileSync(new URL('../atlas/data/'+name,import.meta.url)));
const degree=100/111195.08;
const square={type:'Polygon',coordinates:[[[0,0],[degree,0],[degree,degree],[0,degree],[0,0]]]};
assert.ok(Math.abs(areaHa(square)-1)<0.001,'A 100 m square must cover approximately one hectare');
const hole=[[0,0],[degree/2,0],[degree/2,degree/2],[0,degree/2],[0,0]];
assert.ok(Math.abs(areaHa({...square,coordinates:[square.coordinates[0],hole]})-.75)<.001,'Subtract holes');
assert.ok(Math.abs(areaHa({type:'MultiPolygon',coordinates:[square.coordinates,square.coordinates]})-2)<.002);
const fixture=enrichCensus([0,null,-1,100].map((n,i)=>({type:'Feature',id:String(i),geometry:square,properties:{n_per:n,layer:'census'}})));
assert.equal(fixture[0].properties.density_ha,0);
assert.equal(fixture[1].properties.density_ha,null);assert.equal(fixture[2].properties.density_ha,null);
const sample=summarize(fixture,new Set(['census']));assert.equal(sample.population,100);assert.equal(sample.manzanas,2);assert.equal(sample.missingPopulation,2);assert.ok(Math.abs(sample.density-50)<.05);
const commerce=read('commerce.geojson').features,census=enrichCensus(read('census.geojson').features);
const groups=streetGroups(commerce);
assert.equal(groups.rows.reduce((s,r)=>s+r.count,0)+groups.withoutStreet,commerce.length);
assert.equal(groups.withoutStreet,294);
const selected=groups.rows[0];
const state={active:new Set(['commerce']),query:'',business:'all',heightQuality:'all',permitYear:'all',projectState:'all',street:selected.name};
assert.equal(filterFeatures(commerce,'commerce',state).length,selected.count);
assert.equal(filterFeatures(commerce,'commerce',{...state,street:'nonexistent street'}).length,0);
const real=summarize([...commerce,...census],new Set(['commerce','census']));
const demo=[...read('demoZoning.geojson').features,...read('demoWorks.geojson').features];
const mixed=summarize([...commerce,...census,...demo],new Set(['commerce','census','demoZoning','demoWorks']));
assert.equal(mixed.population,real.population);assert.equal(mixed.commerce,real.commerce);assert.equal(mixed.demo,10);
const manifest=read('manifest.json'),demos=manifest.datasets.filter(d=>d.is_demo);
assert.equal(demos.length,2);assert.ok(demo.every(f=>f.properties.evidence_type==='demo'&&f.properties.name.startsWith('DEMO')));
const exported=csv(demo,manifest.datasets);assert.ok(exported.includes('DEMO SINTÉTICA'));
assert.equal(exported.split('\r\n').length,11);
const contract=JSON.parse(readFileSync(new URL('../atlas/integration-contract.json',import.meta.url)));
assert.equal(contract.status,'not_connected');assert.equal(contract.transport.endpoint,null);
console.log(JSON.stringify({test:'territorial analysis invariants',result:'PASS',commerce:commerce.length,streets:groups.rows.length,withoutStreet:groups.withoutStreet,personsInKnownManzanas:real.population,demos:10}));
